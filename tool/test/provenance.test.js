/* ---- unit: config provenance block (NAR-002-028) --------------------------- */

test('resolveConfig passes the provenance declaration block through, permissively', () => {
  const declared = resolveConfig({
    ...silentRaw(),
    provenance: { script: { authorship: 'mixed', note: 'drafted by agent' }, disclosure: 'AI-assisted' },
  }, {}, '.');
  assert.deepEqual(declared.provenance, {
    script: { authorship: 'mixed', note: 'drafted by agent' },
    disclosure: 'AI-assisted',
  });

  // Unrecognized authorship strings pass through as recorded, never coerced.
  const custom = resolveConfig({
    ...silentRaw(), provenance: { script: { authorship: 'intern + three models' } },
  }, {}, '.');
  assert.equal(custom.provenance.script.authorship, 'intern + three models');

  // Absence is neutral: null, no error.
  assert.equal(resolveConfig(silentRaw(), {}, '.').provenance, null);
});

test('resolveConfig rejects structurally malformed provenance blocks', () => {
  assert.throws(() => resolveConfig({ ...silentRaw(), provenance: 'mixed' }, {}, '.'), /config\.provenance: expected an object/);
  assert.throws(() => resolveConfig({ ...silentRaw(), provenance: { script: { authorship: '' } } }, {}, '.'), /authorship: must be a non-empty string/);
  assert.throws(() => resolveConfig({ ...silentRaw(), provenance: { script: { authorship: 'human' }, disclosure: 42 } }, {}, '.'), /disclosure: must be a non-empty string/);
});

test('provenance declarations do not change execution or proof fingerprints', () => {
  const dir = tmp('narova-prov-fingerprint-');
  const base = resolveConfig(silentRaw(), {}, dir);
  const declared = resolveConfig({
    ...silentRaw(),
    provenance: { script: { authorship: 'agent', note: 'report-only' }, disclosure: 'AI-assisted' },
  }, {}, dir);
  assert.equal(hashConfig(declared), hashConfig(base));
  const out = path.join(dir, 'out');
  writeStageInputs(base, out);
  const before = fs.readFileSync(path.join(out, 'config.resolved.json'), 'utf8');
  writeStageInputs(declared, out);
  const after = fs.readFileSync(path.join(out, 'config.resolved.json'), 'utf8');
  assert.equal(after, before, 'advisory declarations do not alter the runtime projection');
  assert.equal(JSON.parse(after).provenance, undefined);
});

/* ---- unit: origin classes and rights buckets (NAR-005-021) ----------------- */

test('originClass groups recorded origin modes into display classes', () => {
  assert.equal(originClass({ origin: { mode: 'user' } }), 'project-authored or imported');
  assert.equal(originClass({ origin: { mode: 'import' } }), 'project-authored or imported');
  assert.equal(originClass({}), 'project-authored or imported');
  assert.equal(originClass({ origin: { mode: 'stock' } }), 'acquired from a stock provider or URL');
  assert.equal(originClass({ origin: { mode: 'download' } }), 'acquired from a stock provider or URL');
  assert.equal(originClass({ origin: { mode: 'source-page' } }), 'acquired from a stock provider or URL');
  assert.equal(originClass({ origin: { mode: 'generated' } }), 'generated by a media provider');
  assert.equal(originClass({ origin: { mode: 'capture' } }), 'captured by a walkthrough');
});

test('rightsBucket normalizes recorded license facts into display buckets', () => {
  const record = (license, origin = {}) => ({ origin: { mode: 'stock', ...origin }, rights: { status: 'declared', ...(license ? { license } : {}) } });
  assert.equal(rightsBucket(record('CC-BY-4.0')), 'CC-BY');
  assert.equal(rightsBucket(record('cc-by-sa-2.0')), 'CC-BY-SA');
  assert.equal(rightsBucket(record('CC-BY-NC-ND-4.0')), 'CC-BY-NC-ND');
  assert.equal(rightsBucket(record('CC0')), 'public domain');
  assert.equal(rightsBucket(record('Public Domain Mark 1.0')), 'public domain');
  assert.equal(rightsBucket(record('Pexels License', { provider: 'pexels' })), 'provider-licensed');
  assert.equal(rightsBucket(record('some-custom-string')), 'unknown');
  // Absent license: original only for project-authored/imported/captured media.
  assert.equal(rightsBucket({ origin: { mode: 'user' }, rights: { status: 'unknown' } }), 'original');
  assert.equal(rightsBucket({ origin: { mode: 'capture' }, rights: { status: 'unknown' } }), 'original');
  assert.equal(rightsBucket({ origin: { mode: 'stock' }, rights: { status: 'unknown' } }), 'unknown');
  assert.equal(rightsBucket({ origin: { mode: 'generated' }, rights: { status: 'unknown' } }), 'unknown');
});

/* ---- unit: credit entry selection and formats (NAR-005-008, NAR-009-029) --- */

function creditFixture() {
  const dir = tmp('narova-credits-fmt-');
  fs.mkdirSync(path.join(dir, 'assets'));
  const write = name => fs.writeFileSync(path.join(dir, 'assets', name), `bytes-${name}`);
  write('a.jpg'); write('b.jpg'); write('c.jpg'); write('d.jpg');
  registerAsset(dir, {
    file: 'assets/a.jpg',
    origin: { mode: 'stock', provider: 'example', sourcePage: 'https://example.test/a' },
    rights: { license: 'CC-BY-4.0', licenseUrl: 'https://creativecommons.org/licenses/by/4.0/', creator: 'Artist A', attribution: 'Artist A / Example' },
  });
  // Duplicate credit text of a.jpg — deduplicated away in every format.
  registerAsset(dir, {
    file: 'assets/b.jpg',
    origin: { mode: 'stock', provider: 'example', sourcePage: 'https://example.test/a' },
    rights: { license: 'CC-BY-4.0', licenseUrl: 'https://creativecommons.org/licenses/by/4.0/', creator: 'Artist A', attribution: 'Artist A / Example' },
  });
  // Creator only, no license or source page.
  registerAsset(dir, { file: 'assets/c.jpg', rights: { creator: 'Artist C' } });
  // No creator/attribution — appears in no format.
  registerAsset(dir, { file: 'assets/d.jpg', origin: { mode: 'stock', provider: 'example' }, rights: { license: 'CC0' } });
  return dir;
}

test('credit formats derive from the same deduplicated sorted entries', () => {
  const dir = creditFixture();
  try {
    const lines = creditLines(dir);
    const entries = creditEntries(dir);
    assert.deepEqual(entries.map(e => e.line), lines);
    assert.equal(entries.length, 2);

    // Default text is the existing projection, byte-compatible.
    assert.equal(formatCredits(entries, 'text'), lines.join('\n'));
    // youtube: one credit per line, same text without bullets.
    assert.equal(formatCredits(entries, 'youtube'), lines.join('\n'));
    // json: machine-readable entries, null for absent fields.
    const json = JSON.parse(formatCredits(entries, 'json'));
    assert.equal(json.length, 2);
    assert.deepEqual(json.find(e => e.attribution === 'Artist A / Example'), {
      creator: 'Artist A',
      attribution: 'Artist A / Example',
      license: 'CC-BY-4.0',
      licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',
      sourceUrl: 'https://example.test/a',
    });
    assert.deepEqual(json.find(e => e.creator === 'Artist C'), {
      creator: 'Artist C', attribution: null, license: null, licenseUrl: null, sourceUrl: null,
    });
    assert.throws(() => formatCredits(entries, 'xml'), /unknown credits format/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('web credits escape recorded text and link only recorded URLs', () => {
  const dir = tmp('narova-credits-web-');
  try {
    fs.mkdirSync(path.join(dir, 'assets'));
    fs.writeFileSync(path.join(dir, 'assets', 'evil.jpg'), 'x');
    registerAsset(dir, {
      file: 'assets/evil.jpg',
      origin: { mode: 'stock', provider: 'example', sourcePage: 'https://example.test/item' },
      rights: {
        attribution: '<script>alert("x")</script> & Co',
        license: 'CC-BY-4.0',
        licenseUrl: 'https://creativecommons.org/licenses/by/4.0/?lang=en&x=1',
      },
    });
    const entries = creditEntries(dir);
    const web = formatCredits(entries, 'web');
    assert.ok(!web.includes('<script>'), 'recorded markup must be escaped');
    assert.match(web, /&lt;script&gt;/);
    assert.match(web, /&amp; Co/);
    assert.match(web, /<a href="https:\/\/creativecommons\.org\/licenses\/by\/4\.0\/\?lang=en&amp;x=1">CC-BY-4\.0<\/a>/);
    assert.match(web, /<a href="https:\/\/example\.test\/item">https:\/\/example\.test\/item<\/a>/);
    // Only recorded URLs become links — the recorded license text is the anchor.
    assert.equal(web.match(/<a href=/g).length, 2);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

