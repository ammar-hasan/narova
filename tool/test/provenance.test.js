/* Fully documented narrated project: claims ledger, tracked media with rights,
 * one generated clip with a recipe, declared authorship, current manifest. */
function documentedProject() {
  const dir = tmp('narova-prov-doc-');
  fs.mkdirSync(path.join(dir, 'assets'));
  fs.writeFileSync(path.join(dir, 'reel.config.mjs'), `export default {
  title: 'Doc Project',
  voices: { a: { speaker: 'en_US-lessac-medium', backend: 'piper' } },
  provenance: { script: { authorship: 'mixed', note: 'drafted by agent, reviewed by human' }, disclosure: 'Contains AI-generated media' },
  scenes: [
    { id: 'intro', body: '<p>i</p>', vo: [{ who: 'a', text: 'Ninety percent of users love it.' }] },
    { id: 'main', body: '<p>m</p>', vo: [{ who: 'a', text: 'It runs two times faster.' }] },
  ],
};
`);
  fs.writeFileSync(path.join(dir, 'claims.md'), '# Claims\n\n- Ninety percent of users love it (survey)\n- two times faster (benchmark)\n');
  fs.writeFileSync(path.join(dir, 'assets', 'hero.jpg'), 'hero-bytes');
  fs.writeFileSync(path.join(dir, 'assets', 'gen-clip.mp4'), 'clip-bytes');
  const clipFile = path.join(dir, 'assets', 'gen-clip.mp4');
  const recipe = {
    kind: 'narova-generate-spec', version: 1, provider: 'sora', model: 'sora-2', prompt: 'rain',
    artifact: 'gen-clip.mp4', artifactBytes: fs.statSync(clipFile).size,
    artifactSha256: sha256File(clipFile),
  };
  fs.writeFileSync(path.join(dir, 'assets', 'gen-clip.gen.json'), `${JSON.stringify(recipe)}\n`);
  const imported = run([
    'assets', 'import', 'assets/hero.jpg', '--project', dir,
    '--origin', 'stock', '--provider', 'example', '--source-page', 'https://example.test/hero',
    '--license', 'CC-BY-4.0', '--attribution', 'Example Artist',
  ]);
  assert.equal(imported.status, 0, imported.stderr);
  const lock = JSON.parse(fs.readFileSync(path.join(dir, 'assets.lock.json'), 'utf8'));
  const clipStat = fs.statSync(path.join(dir, 'assets', 'gen-clip.mp4'));
  lock.assets.push({
    file: 'assets/gen-clip.mp4', sha256: sha256File(path.join(dir, 'assets', 'gen-clip.mp4')),
    bytes: clipStat.size, kind: 'video',
    origin: { mode: 'generated', provider: 'sora', model: 'sora-2' },
    rights: { status: 'unknown' }, acquiredAt: '2026-08-19T00:00:00.000Z',
    recipe: 'assets/gen-clip.gen.json',
  });
  fs.writeFileSync(path.join(dir, 'assets.lock.json'), JSON.stringify(lock, null, 2) + '\n');
  const compiled = run(['compile', '--project', dir]);
  assert.equal(compiled.status, 0, compiled.stderr);
  // Keep this fixture deterministic across machines while exercising report
  // consumption of a compile-time backend version. The compile path itself is
  // covered in manifest.test.js with a registered provider identity.
  const manifestFile = path.join(dir, 'out', 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  assert.equal(typeof manifest.renderer.providerVersion, 'string');
  manifest.environment.backendVersion = 'piper-test-1';
  fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2));
  return dir;
}

