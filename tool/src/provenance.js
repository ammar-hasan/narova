'use strict';
/* Read-only project provenance report (NAR-005-019..021, NAR-009-028).
 *
 * The report is composed at command time from existing project evidence only:
 * the resolved config, the claims ledger, the asset registry, the asset
 * directory listing, and the build manifest. It never synthesizes, browses,
 * renders, encodes, probes tools, touches the network, or mutates a file.
 *
 * Every fact carries exactly one grade:
 *   verified — backed by a citable project artifact (digest match, manifest
 *              field, registry record, generation recipe);
 *   declared — an authored statement of record (config provenance block,
 *              registry rights declarations);
 *   unknown  — not recorded or not declared.
 * Declared facts are never presented as verified. */
const fs = require('fs');
const path = require('path');
const { findClaims, readClaimsLedger, matchClaim } = require('./check');
const {
  readAssetLock, resolveProjectFile, sha256File, inferKind, ASSET_LOCK_FILE,
} = require('./asset-registry');
const { hashConfig, validate: validateManifest } = require('./manifest');

const GRADE_MARK = { verified: '✓', declared: '○', unknown: '?' };
const REMIX_LINEAGE_FILE = '.narova-remix.json';
const CONTROL_RE = /[\u0000-\u001f\u007f-\u009f]/;

function lineageText(value, label, max = 512) {
  if (typeof value !== 'string' || !value || value.length > max || CONTROL_RE.test(value)) {
    throw new Error(`${label} must be a bounded non-empty string without control characters`);
  }
  return value;
}

function validateLineageParent(parent) {
  if (!parent || typeof parent !== 'object' || Array.isArray(parent)) throw new Error('expected a parent record');
  const kind = lineageText(parent.kind, 'parent kind', 16);
  if (!['project', 'archive', 'github'].includes(kind)) throw new Error(`unsupported parent kind: ${kind}`);
  if (kind === 'project' || kind === 'archive') {
    if (!/^[a-f0-9]{64}$/.test(parent.identity || '')) throw new Error(`${kind} parent identity must be a lowercase SHA-256 digest`);
    return { kind, identity: parent.identity };
  }
  const locator = lineageText(parent.locator, 'GitHub parent locator');
  if (!/^github:[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+(?:#[^\s]+)?$/.test(locator)) throw new Error('GitHub parent locator is invalid');
  if (!/^[a-f0-9]{40}$/i.test(parent.commit || '')) throw new Error('GitHub parent commit must be a 40-character digest');
  return { kind, locator, commit: parent.commit.toLowerCase() };
}

/* Origin modes recorded in the registry, grouped into display classes. */
const ORIGIN_CLASSES = [
  'project-authored or imported',
  'acquired from a stock provider or URL',
  'generated by a media provider',
  'captured by a walkthrough',
];

function originClass(record) {
  const mode = (record.origin && record.origin.mode) || 'user';
  if (mode === 'generated') return 'generated by a media provider';
  if (mode === 'capture') return 'captured by a walkthrough';
  if (mode === 'stock' || mode === 'download' || mode === 'source-page') {
    return 'acquired from a stock provider or URL';
  }
  return 'project-authored or imported';
}

/* Rights display buckets (NAR-005-021): a display projection keyed only on
 * recorded registry facts — never a legal determination. The recorded license
 * string is always displayed beside the bucket; unrecognized or absent values
 * land in `unknown`. */
function rightsBucket(record) {
  const license = record.rights && record.rights.license;
  const mode = (record.origin && record.origin.mode) || 'user';
  if (!license) {
    return ['user', 'import', 'capture'].includes(mode) ? 'original' : 'unknown';
  }
  if (/^cc[- ]?0\b/i.test(license) || /public[\s-]?domain/i.test(license)) return 'public domain';
  const cc = license.match(/^cc[- ]?(by(?:[- ](?:nc-sa|nc-nd|sa|nc|nd))?)/i);
  if (cc) return `CC-${cc[1].toUpperCase().replace(/[- ]+/g, '-')}`;
  if (record.origin && record.origin.provider) return 'provider-licensed';
  return 'unknown';
}

/* License-string recognition for the import/download advisory (NAR-016-059).
 * Advisory only — recognition never gates storage and never changes the
 * rightsBucket display mapping above. Recognized forms: `public domain`
 * spellings, `cc0`, and the familiar Creative Commons identifiers (cc-by,
 * cc-by-sa, cc-by-nc, cc-by-nd and their combinations) with an optional
 * version suffix or creativecommons.org URL form. */
const CC_LICENSE_URL_RE = /^https?:\/\/(www\.)?creativecommons\.org\/(licenses|publicdomain)\//i;
function recognizedLicense(license) {
  const value = String(license || '').trim();
  if (!value) return false;
  if (/^cc[- ]?0\b/i.test(value) || /public[\s-]?domain/i.test(value)) return true;
  if (/^cc[- ]?by(?:[- ](?:nc-sa|nc-nd|sa|nc|nd))?(?=[- ]|$)/i.test(value)) return true;
  return CC_LICENSE_URL_RE.test(value);
}

function bucketSortKey(bucket) {
  const order = ['original', 'public domain'];
  const i = order.indexOf(bucket);
  if (i !== -1) return `0${i}`;
  if (bucket.startsWith('CC-')) return `1${bucket}`;
  if (bucket === 'provider-licensed') return '2';
  return '3'; // unknown last
}

/* Read the registry when it exists; absent or unreadable degrades the media
 * section to "not recorded" instead of failing the report. */
function readRegistry(projectDir) {
  const file = path.join(path.resolve(projectDir || '.'), ASSET_LOCK_FILE);
  if (!fs.existsSync(file)) return { records: null, note: null };
  try {
    return { records: readAssetLock(projectDir).assets, note: null };
  } catch (error) {
    return { records: null, note: `registry unreadable: ${error.message}` };
  }
}

function containedProjectFile(projectDir, file) {
  const root = path.resolve(projectDir || '.');
  const absolute = path.resolve(file);
  const lexical = path.relative(root, absolute);
  if (!lexical || lexical === '..' || lexical.startsWith(`..${path.sep}`) || path.isAbsolute(lexical)) {
    throw new Error(`file escapes the project: ${file}`);
  }
  const rootReal = fs.realpathSync(root);
  const fileReal = fs.realpathSync(absolute);
  const realRelative = path.relative(rootReal, fileReal);
  if (!realRelative || realRelative === '..' || realRelative.startsWith(`..${path.sep}`)
      || path.isAbsolute(realRelative)) {
    throw new Error(`file resolves outside the project: ${file}`);
  }
  return absolute;
}

function readManifest(config, outDir) {
  const projectDir = config.projectDir || '.';
  const file = path.join(outDir, 'manifest.json');
  let stat;
  try {
    stat = fs.lstatSync(file);
  } catch (error) {
    if (error.code === 'ENOENT') return { parsed: null, file, note: null };
    return { parsed: null, file, note: `manifest unreadable: ${error.message}` };
  }
  try {
    containedProjectFile(projectDir, file);
  } catch (error) {
    return { parsed: null, file, note: `manifest unreadable: ${error.message}` };
  }
  if (!stat.isFile()) {
    return { parsed: null, file, note: 'manifest unreadable: expected a regular file, not a symlink or directory' };
  }
  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    return { parsed: null, file, note: `manifest unreadable: ${error.message}` };
  }
  let errors;
  try { errors = validateManifest(parsed); }
  catch (error) { return { parsed: null, file, note: `manifest invalid: ${error.message}` }; }
  if (errors.length) return { parsed: null, file, note: `manifest invalid: ${errors.join('; ')}` };
  const recordedConfigHash = parsed.hashes && parsed.hashes.config;
  const currentConfigHash = hashConfig(config);
  const current = typeof recordedConfigHash === 'string' && recordedConfigHash === currentConfigHash;
  const currentNote = current
    ? null
    : recordedConfigHash
      ? 'manifest does not match the current resolved project config'
      : 'manifest does not record a current-config binding';
  return { parsed, file, note: null, current, currentNote };
}

/* Integrity of one tracked record against the current file bytes — the same
 * verification boundary as `assets verify` (digest, size, kind), computed
 * directly so the report never spawns a media probe. */
function recordIntegrity(projectDir, record) {
  let inspected;
  try {
    const { absolute } = resolveProjectFile(projectDir, record.file);
    inspected = { sha256: sha256File(absolute), bytes: fs.statSync(absolute).size, kind: inferKind(record.file) };
  } catch (error) {
    return { status: 'failed', grade: 'verified', issues: [error.message] };
  }
  const issues = [];
  if (inspected.sha256 !== record.sha256) issues.push('content hash changed');
  if (inspected.bytes !== record.bytes) issues.push(`size changed (${record.bytes} -> ${inspected.bytes})`);
  if (inspected.kind !== record.kind) issues.push(`kind changed (${record.kind} -> ${inspected.kind})`);
  return issues.length
    ? { status: 'failed', grade: 'verified', issues }
    : { status: 'ok', grade: 'verified', issues: [] };
}

/* Files in the configured asset directory that no registry record tracks.
 * Recipe sidecars referenced by a record count as tracked. */
function scanUntracked(config, records) {
  if (!config.assetsDir) return null;
  const projectDir = path.resolve(config.projectDir || '.');
  try {
    const projectReal = fs.realpathSync(projectDir);
    const assetsReal = fs.realpathSync(config.assetsDir);
    const rel = path.relative(projectReal, assetsReal);
    if (!rel || rel === '..' || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel)) {
      return { count: null, files: [], note: 'configured asset directory resolves outside the project' };
    }
  } catch (error) {
    return { count: null, files: [], note: `asset directory unreadable: ${error.message}` };
  }
  const tracked = new Set();
  for (const record of records || []) {
    tracked.add(record.file);
    if (record.recipe) tracked.add(record.recipe);
  }
  const files = [];
  function visit(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(full);
      else files.push(full);
    }
  }
  try { visit(config.assetsDir); }
  catch (error) { return { count: null, files: [], note: `asset directory unreadable: ${error.message}` }; }
  const untracked = files
    .map(file => path.relative(projectDir, file).split(path.sep).join('/'))
    .filter(rel => !tracked.has(rel))
    .sort();
  return { count: untracked.length, files: untracked };
}

function configName(opts, projectDir) {
  return opts.configFile
    ? path.relative(projectDir, opts.configFile) || path.basename(opts.configFile)
    : 'reel.config';
}

function resolvedOverrideSource(opts, key, projectDir) {
  if (opts.cliOverrides && Object.prototype.hasOwnProperty.call(opts.cliOverrides, key)) {
    const flag = key === 'voiceA' ? 'voice-a' : key === 'voiceB' ? 'voice-b' : key;
    return `command --${flag}`;
  }
  if (opts.restoredOverrides && Object.prototype.hasOwnProperty.call(opts.restoredOverrides, key)) {
    return path.relative(projectDir, path.join(opts.outDir, '.restored-overrides.json'));
  }
  return null;
}

function joinedSources(...sources) {
  return [...new Set(sources.flat().filter(Boolean))].join(' + ');
}

function collectClaims(config, opts = {}) {
  const projectDir = config.projectDir || '.';
  const configSource = configName(opts, projectDir);
  const variantSource = resolvedOverrideSource(opts, 'variant', projectDir);
  const voTurns = (config.scenes || []).reduce((n, s) => n + (s.vo ? s.vo.length : 0), 0);
  const detected = findClaims(config);
  let ledger = null;
  let ledgerNote = null;
  const ledgerName = ['claims.md', 'CLAIMS.md'].find(name => {
    try { fs.lstatSync(path.join(projectDir, name)); return true; }
    catch (error) { return error.code !== 'ENOENT'; }
  });
  try {
    if (ledgerName) resolveProjectFile(projectDir, ledgerName);
    ledger = readClaimsLedger(config);
  } catch (error) {
    ledgerNote = `claims ledger unreadable: ${error.message}`;
  }
  const rows = detected.map(claim => {
    if (ledgerNote) {
      return {
        ref: claim.ref,
        status: 'unknown',
        grade: 'unknown',
        source: joinedSources(configSource, variantSource, ledgerName),
      };
    }
    const sourced = !!(ledger && matchClaim(claim.text, ledger));
    return {
      ref: claim.ref,
      status: sourced ? 'sourced' : 'unsupported',
      grade: sourced ? 'verified' : 'unknown',
      source: joinedSources(
        configSource,
        variantSource,
        sourced ? path.relative(projectDir, ledger.path) : null,
      ),
    };
  });
  return {
    voTurns,
    detected: rows.length,
    sourced: ledgerNote ? null : rows.filter(r => r.status === 'sourced').length,
    unsupported: ledgerNote ? null : rows.filter(r => r.status === 'unsupported').length,
    unknown: rows.filter(r => r.status === 'unknown').length,
    ledger: ledger ? path.relative(projectDir, ledger.path) : null,
    ledgerNote,
    rows,
    limit: 'claim detection is a heuristic — it does not detect every factual claim, and a ledger match does not verify that the source is correct',
  };
}

function recipeEvidence(projectDir, record) {
  if (!record.recipe) {
    return { path: null, grade: 'unknown', status: 'not recorded', issue: null };
  }
  try {
    const { absolute } = resolveProjectFile(projectDir, record.recipe);
    const parsed = JSON.parse(fs.readFileSync(absolute, 'utf8'));
    const supportedVersion = parsed && (parsed.version === 1 || parsed.version === 2);
    const currentIdentity = parsed && parsed.version === 2
      && typeof parsed.providerName === 'string' && parsed.providerName.trim()
      && parsed.providerProtocol === 'narova-video-provider/v1'
      && typeof parsed.providerVersion === 'string' && parsed.providerVersion.trim()
      && parsed.params && typeof parsed.params === 'object' && !Array.isArray(parsed.params);
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)
        || parsed.kind !== 'narova-generate-spec' || !supportedVersion
        || typeof parsed.provider !== 'string' || !parsed.provider.trim()
        || typeof parsed.prompt !== 'string' || !parsed.prompt.trim()
        || (parsed.version === 2 && !currentIdentity)) {
      throw new Error('generation recipe is not a supported narova-generate-spec version 1 or 2 record with provider identity and prompt');
    }
    const expectedArtifact = path.basename(record.file);
    if (parsed.artifact !== expectedArtifact
        || parsed.artifactBytes !== record.bytes
        || parsed.artifactSha256 !== record.sha256) {
      throw new Error('generation recipe artifact identity does not match the tracked media record');
    }
    const origin = record.origin || {};
    if (origin.provider && parsed.provider !== origin.provider) {
      throw new Error('generation recipe provider does not match the tracked media record');
    }
    if (origin.model && parsed.model !== origin.model) {
      throw new Error('generation recipe model does not match the tracked media record');
    }
    return { path: record.recipe, grade: 'verified', status: 'available', issue: null };
  } catch (error) {
    return { path: record.recipe, grade: 'unknown', status: 'unavailable', issue: error.message };
  }
}

function collectMedia(config, registry) {
  const projectDir = config.projectDir || '.';
  const records = registry.records || [];
  const rows = records.map(record => {
    const rights = record.rights || {};
    const declared = !!(rights.license || rights.creator || rights.attribution
      || (rights.status && rights.status !== 'unknown'));
    return {
      file: record.file,
      kind: record.kind,
      originClass: originClass(record),
      originMode: (record.origin && record.origin.mode) || 'user',
      integrity: recordIntegrity(projectDir, record),
      rights: {
        bucket: rightsBucket(record),
        license: rights.license || null,
        status: rights.status || 'unknown',
        // Rights metadata is an authored declaration (NAR-005-006) — never verified.
        grade: declared ? 'declared' : 'unknown',
      },
    };
  });
  const originClasses = {};
  const buckets = {};
  for (const row of rows) {
    originClasses[row.originClass] = (originClasses[row.originClass] || 0) + 1;
    buckets[row.rights.bucket] = (buckets[row.rights.bucket] || 0) + 1;
  }
  return {
    registry: registry.records ? ASSET_LOCK_FILE : null,
    registryNote: registry.note,
    tracked: rows.length,
    rows,
    originClasses,
    buckets,
    untracked: scanUntracked(config, records),
    hashCoverage: registry.records
      ? { hashed: records.filter(r => typeof r.sha256 === 'string' && r.sha256).length, total: records.length }
      : null,
  };
}

function manifestSpeechVersion(manifest, backend) {
  const parsed = manifest && manifest.parsed;
  const environmentVersion = parsed && parsed.environment && parsed.environment.backendVersion;
  if (typeof environmentVersion === 'string' && environmentVersion.trim()) return environmentVersion;
  const voice = Object.values((parsed && parsed.voices) || {})
    .find(value => value && value.backend === backend && typeof value.providerVersion === 'string' && value.providerVersion.trim());
  return voice ? voice.providerVersion : null;
}

function collectAiGeneration(config, registry, media, opts, manifest) {
  const projectDir = config.projectDir || '.';
  const source = configName(opts, projectDir);
  const backendOverrideSource = resolvedOverrideSource(opts, 'backend', projectDir);
  const tempoOverrideSource = resolvedOverrideSource(opts, 'tempo', projectDir);
  const variantOverrideSource = resolvedOverrideSource(opts, 'variant', projectDir);
  const speakerOverrideSources = [
    resolvedOverrideSource(opts, 'voiceA', projectDir),
    resolvedOverrideSource(opts, 'voiceB', projectDir),
  ];
  const voTurns = (config.scenes || []).reduce((n, s) => n + (s.vo ? s.vo.length : 0), 0);
  let narration;
  if (config.narrationSource) {
    narration = {
      status: 'external',
      file: path.relative(projectDir, config.narrationSource.file),
      grade: 'verified',
      source,
    };
  } else if (voTurns === 0) {
    narration = { status: 'none', grade: 'unknown', source: null };
  } else {
    const voices = Object.entries(config.voices || {}).map(([id, v], index) => ({
      id, backend: v.backend || null, speaker: v.speaker || null,
      source: joinedSources(source, backendOverrideSource, speakerOverrideSources[index]),
    }));
    const manifestBackend = manifest && manifest.current && manifest.parsed && manifest.parsed.environment
      ? manifest.parsed.environment.backend : null;
    const backendVersion = manifestBackend ? manifestSpeechVersion(manifest, manifestBackend) : null;
    const synthesized = !!(manifest && manifest.current && manifest.parsed
      && manifest.parsed.stages && manifest.parsed.stages.synth);
    const manifestSource = synthesized ? path.relative(projectDir, manifest.file) : null;
    narration = {
      status: synthesized ? 'synthesized' : 'configured',
      voices,
      grade: 'verified',
      source: joinedSources(
        voices.map(voice => voice.source), tempoOverrideSource, variantOverrideSource, manifestSource,
      ),
      backendVersion,
      backendVersionGrade: backendVersion ? 'verified' : 'unknown',
      backendVersionSource: backendVersion ? path.relative(projectDir, manifest.file) : null,
    };
  }
  const generatedMedia = (registry.records || [])
    .filter(record => ((record.origin && record.origin.mode) || 'user') === 'generated')
    .map(record => {
      const recipe = recipeEvidence(projectDir, record);
      return {
        file: record.file,
        provider: record.origin.provider || null,
        model: record.origin.model || null,
        recipe: recipe.path,
        recipeGrade: recipe.grade,
        recipeStatus: recipe.status,
        recipeIssue: recipe.issue,
        grade: 'verified',
        source: ASSET_LOCK_FILE,
      };
    });
  const provenance = config.provenance || null;
  const scriptAuthorship = provenance && provenance.script
    ? {
      value: provenance.script.authorship,
      recognized: ['agent', 'human', 'mixed'].includes(provenance.script.authorship),
      note: provenance.script.note || null,
      grade: 'declared',
      source,
    }
    : { value: null, grade: 'unknown', source: null };
  const disclosure = provenance && provenance.disclosure
    ? { value: provenance.disclosure, grade: 'declared', source }
    : null;
  const untrackedIncomplete = !!(media.untracked
    && (media.untracked.count == null || media.untracked.count > 0));
  const registryIncomplete = registry.records == null && registry.note != null;
  const recipeIncomplete = generatedMedia.some(item => item.recipeGrade !== 'verified');
  const incomplete = registryIncomplete || untrackedIncomplete || recipeIncomplete;
  const incompleteReasons = [];
  if (registryIncomplete) incompleteReasons.push('the asset registry could not be inspected');
  if (untrackedIncomplete) incompleteReasons.push(media.untracked.count == null
    ? 'the configured asset directory could not be inspected safely'
    : 'untracked files in the asset directory may include generated media');
  if (recipeIncomplete) incompleteReasons.push('one or more generated-media recipes are not available');
  return {
    narration,
    generatedMedia,
    scriptAuthorship,
    disclosure,
    incomplete,
    incompleteNote: incomplete ? `generation provenance is incomplete — ${incompleteReasons.join('; ')}` : null,
  };
}

function collectReproducibility(config, registry, media, opts, manifest) {
  const projectDir = config.projectDir || '.';
  const source = configName(opts, projectDir);
  const raw = opts.raw || {};
  const rendererOverrideSource = resolvedOverrideSource(opts, 'renderer', projectDir);
  const backendOverrideSource = resolvedOverrideSource(opts, 'backend', projectDir);
  const manifestRel = manifest.parsed ? path.relative(projectDir, manifest.file) : null;
  const manifestFact = manifest.parsed
    ? {
      path: manifestRel,
      schema: manifest.parsed.version || null,
      tool: manifest.parsed.narova || (manifest.parsed.environment && manifest.parsed.environment.narova) || null,
      grade: 'verified',
      source: manifestRel,
      currentConfig: manifest.current,
      ...(manifest.currentNote ? { note: manifest.currentNote } : {}),
    }
    : { path: null, grade: 'unknown', source: null, note: manifest.note };
  let renderer;
  const manifestRenderer = manifest.current && manifest.parsed && manifest.parsed.renderer;
  if (manifestRenderer && manifestRenderer.provider) {
    const version = typeof manifestRenderer.providerVersion === 'string' && manifestRenderer.providerVersion.trim()
      ? manifestRenderer.providerVersion : null;
    renderer = {
      provider: manifestRenderer.provider,
      version,
      grade: 'verified',
      source: joinedSources(manifestRel, rendererOverrideSource),
      versionGrade: version ? 'verified' : 'unknown',
      versionSource: version ? manifestRel : null,
    };
  } else if (raw.renderer != null || rendererOverrideSource) {
    renderer = { provider: config.renderer, version: null, grade: 'verified', source: rendererOverrideSource || source, versionGrade: 'unknown', versionSource: null };
  } else {
    renderer = { provider: null, version: null, grade: 'unknown', source: null, versionGrade: 'unknown', versionSource: null };
  }
  let speech;
  const envBackend = manifest.current && manifest.parsed && manifest.parsed.environment && manifest.parsed.environment.backend;
  const voiceEntries = Object.entries(config.voices || {});
  if (envBackend) {
    const version = manifestSpeechVersion(manifest, envBackend);
    speech = {
      backend: envBackend,
      version,
      grade: 'verified',
      source: joinedSources(manifestRel, backendOverrideSource),
      versionGrade: version ? 'verified' : 'unknown',
      versionSource: version ? manifestRel : null,
    };
  } else if (voiceEntries.length && (raw.voices != null || backendOverrideSource)) {
    const backends = [...new Set(voiceEntries.map(([, v]) => v.backend).filter(Boolean))];
    speech = { backend: backends.length === 1 ? backends[0] : backends, version: null, grade: 'verified', source: backendOverrideSource || source, versionGrade: 'unknown', versionSource: null };
  } else {
    speech = { backend: null, version: null, grade: 'unknown', source: null, versionGrade: 'unknown', versionSource: null };
  }
  return {
    manifest: manifestFact,
    assetHashes: media.hashCoverage
      ? { ...media.hashCoverage, basis: `${ASSET_LOCK_FILE} rows` }
      : { hashed: null, total: null, basis: null },
    renderer,
    speech,
  };
}

function collectLineage(projectDir) {
  const file = path.join(projectDir, REMIX_LINEAGE_FILE);
  if (!fs.existsSync(file)) return { parent: null, grade: 'unknown', source: null };
  try {
    const stat = fs.lstatSync(file);
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error('expected a regular project file');
    const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!parsed || parsed.schema !== 'narova.remix/1' || !parsed.parent
        || typeof parsed.parent !== 'object') {
      throw new Error('expected schema narova.remix/1 with a parent record');
    }
    return { parent: validateLineageParent(parsed.parent), grade: 'declared', source: REMIX_LINEAGE_FILE };
  } catch (error) {
    return { parent: null, grade: 'unknown', source: REMIX_LINEAGE_FILE, note: `remix lineage unreadable: ${error.message}` };
  }
}

/* Compose the full graded report from existing project evidence. */
function collectProvenance(config, opts = {}) {
  const projectDir = config.projectDir || '.';
  const registry = readRegistry(projectDir);
  const manifest = readManifest(config, opts.outDir || path.join(projectDir, 'out'));
  const claims = collectClaims(config, opts);
  const media = collectMedia(config, registry);
  const aiGeneration = collectAiGeneration(config, registry, media, opts, manifest);
  const reproducibility = collectReproducibility(config, registry, media, opts, manifest);
  return {
    project: { title: config.title || 'narova', dir: path.resolve(projectDir) },
    lineage: collectLineage(path.resolve(projectDir)),
    claims,
    media,
    aiGeneration,
    reproducibility,
  };
}

/* ---- prose rendering ------------------------------------------------------- */

function formatClaims(claims) {
  const lines = ['Claims'];
  if (claims.voTurns === 0) {
    lines.push('  no narration turns — no claims to detect');
  } else if (claims.detected === 0) {
    lines.push(`  0 claims detected (of ${claims.voTurns} vo turns) — this is the limit of the heuristic, not a perfect score`);
  } else if (claims.ledgerNote) {
    lines.push(`  ${claims.detected} detected, sourcing coverage unknown (of ${claims.voTurns} vo turns; claims ledger unreadable)`);
    for (const row of claims.rows) lines.push(`  ? ${row.ref} — unknown`);
  } else {
    lines.push(`  ${claims.detected} detected, ${claims.sourced} sourced, ${claims.unsupported} unsupported (of ${claims.voTurns} vo turns${claims.ledger ? `; ledger: ${claims.ledger}` : '; no claims ledger'})`);
    for (const row of claims.rows) {
      lines.push(`  ${GRADE_MARK[row.grade]} ${row.ref} — ${row.status}${row.source ? ` (${row.source})` : ''}`);
    }
  }
  if (claims.ledgerNote) lines.push(`  ? ${claims.ledgerNote}`);
  lines.push(`  note: ${claims.limit}.`);
  return lines;
}

function formatMedia(media) {
  const lines = ['Media'];
  if (!media.registry) {
    lines.push(`  tracked media: ? not recorded${media.registryNote ? ` (${media.registryNote})` : ' (no asset registry)'}`);
  } else if (media.tracked === 0) {
    lines.push(`  0 tracked records (${media.registry})`);
  } else {
    lines.push(`  ${media.tracked} tracked records (${media.registry})`);
    for (const cls of ORIGIN_CLASSES) {
      const rows = media.rows.filter(row => row.originClass === cls);
      if (!rows.length) continue;
      lines.push(`  ${cls} (${rows.length}):`);
      for (const row of rows) {
        const license = row.rights.license ? ` (recorded: ${row.rights.license})` : ' (no license recorded)';
        const rightsNote = row.rights.grade === 'declared' ? 'rights declared, not verified' : 'no rights declared';
        const rightsFact = `${GRADE_MARK[row.rights.grade]} ${row.rights.bucket}${license}; ${rightsNote}`;
        if (row.integrity.status === 'failed') {
          lines.push(`    ✗ ${row.file} [${row.kind}] — failed verification (${row.integrity.issues.join('; ')}); ${rightsFact}`);
        } else {
          lines.push(`    ✓ ${row.file} [${row.kind}] — integrity verified; ${rightsFact}`);
        }
      }
    }
    const bucketList = Object.keys(media.buckets)
      .sort((a, b) => bucketSortKey(a).localeCompare(bucketSortKey(b)))
      .map(bucket => `${media.buckets[bucket]} ${bucket}`)
      .join(', ');
    lines.push(`  rights buckets: ${bucketList} (basis: tracked rows above; a display projection, not a legal determination)`);
    lines.push('  note: rights are recorded declarations, not verified permission.');
  }
  if (media.untracked) {
    if (media.untracked.count == null) {
      lines.push(`  untracked in the asset directory: ? not recorded (${media.untracked.note})`);
      lines.push('  note: exact used-asset closure is not established — the asset directory could not be inspected safely.');
    } else if (media.untracked.count > 0) {
      lines.push(`  untracked in the asset directory: ${media.untracked.count} (${media.untracked.files.join(', ')})`);
      lines.push('  note: exact used-asset closure is not established — untracked files exist in the asset directory.');
    } else {
      lines.push('  untracked in the asset directory: 0 (directory scan; every file is tracked)');
    }
  } else {
    lines.push('  asset directory: ? not recorded (no configured asset directory to scan)');
  }
  return lines;
}

function formatAiGeneration(ai) {
  const lines = ['AI generation'];
  const n = ai.narration;
  if (n.status === 'none') {
    lines.push('  narration: none (silent project)');
  } else if (n.status === 'external') {
    lines.push(`  ${GRADE_MARK[n.grade]} narration: external recording — ${n.file} (${n.source})`);
  } else {
    const voices = n.voices.map(v => `${v.id} (${[v.backend, v.speaker].filter(Boolean).join(' / ')})`).join(', ');
    const version = n.backendVersion
      ? `${n.backendVersion} (${n.backendVersionSource})`
      : 'not recorded';
    lines.push(`  ${GRADE_MARK[n.grade]} narration: ${n.status} — ${voices || 'no voices recorded'} (${n.source}); backend version ${version}`);
  }
  if (!ai.generatedMedia.length) {
    lines.push(`  generated media: none recorded${ai.incomplete ? ` — ${ai.incompleteNote}` : ''}`);
  } else {
    lines.push(`  generated media (${ai.generatedMedia.length}):`);
    for (const item of ai.generatedMedia) {
      const detail = [item.provider, item.model].filter(Boolean).join(' / ') || 'provider not recorded';
      const recipe = item.recipeGrade === 'verified'
        ? `; ${GRADE_MARK.verified} recipe ${item.recipe}`
        : item.recipe
          ? `; ${GRADE_MARK.unknown} recipe ${item.recipe} unavailable${item.recipeIssue ? ` (${item.recipeIssue})` : ''}`
          : `; ${GRADE_MARK.unknown} recipe not recorded`;
      lines.push(`    ${GRADE_MARK[item.grade]} ${item.file} — ${detail} (${item.source})${recipe}`);
    }
    if (ai.incomplete) lines.push(`  note: ${ai.incompleteNote}.`);
  }
  const sa = ai.scriptAuthorship;
  if (sa.grade === 'declared') {
    const note = sa.note ? ` — "${sa.note}"` : '';
    lines.push(`  ${GRADE_MARK.declared} script authorship: declared ${sa.value}${note} (${sa.source}) — an authored declaration, not verified`);
  } else {
    lines.push('  ? script authorship: not declared');
  }
  if (ai.disclosure) {
    lines.push(`  ${GRADE_MARK.declared} disclosure: declared "${ai.disclosure.value}" (${ai.disclosure.source}) — an authored declaration, not verified`);
  }
  return lines;
}

function formatReproducibility(repro) {
  const lines = ['Reproducibility'];
  if (repro.manifest.grade === 'verified') {
    lines.push(`  ✓ manifest: ${repro.manifest.path} (schema ${repro.manifest.schema || 'not recorded'}, narova ${repro.manifest.tool || 'not recorded'})${repro.manifest.note ? `; ? ${repro.manifest.note}` : ''}`);
  } else {
    lines.push(`  ? manifest: not recorded (${repro.manifest.note || 'no out/manifest.json'})`);
  }
  if (repro.assetHashes.total != null) {
    lines.push(`  asset hashes: ${repro.assetHashes.hashed} of ${repro.assetHashes.total} tracked records carry digests (basis: ${repro.assetHashes.basis})`);
  } else {
    lines.push('  asset hashes: ? not recorded (no asset registry)');
  }
  if (repro.renderer.grade === 'verified') {
    lines.push(`  ✓ renderer: ${repro.renderer.provider} (${repro.renderer.source}); version ${repro.renderer.version || 'not recorded'}`);
  } else {
    lines.push('  ? renderer: not recorded (no manifest; config does not declare one)');
  }
  if (repro.speech.grade === 'verified') {
    lines.push(`  ✓ speech backend: ${repro.speech.backend} (${repro.speech.source}); version ${repro.speech.version || 'not recorded'}`);
  } else {
    lines.push('  ? speech backend: not recorded');
  }
  return lines;
}

function formatProvenance(report) {
  const lineage = report.lineage && report.lineage.parent
    ? `remix parent: ${GRADE_MARK.declared} recorded ${report.lineage.parent.kind} ${report.lineage.parent.identity || report.lineage.parent.locator || report.lineage.parent.path || ''} (${report.lineage.source}) — lineage, not verified ownership or permission`
    : `remix parent: ? not recorded${report.lineage && report.lineage.note ? ` (${report.lineage.note})` : ''}`;
  return [
    `provenance: ${report.project.title}`,
    `project: ${report.project.dir}`,
    lineage,
    '',
    ...formatClaims(report.claims),
    '',
    ...formatMedia(report.media),
    '',
    ...formatAiGeneration(report.aiGeneration),
    '',
    ...formatReproducibility(report.reproducibility),
  ].join('\n');
}

